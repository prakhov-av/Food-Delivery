/**
 * Ветка обработки запроса чата.
 *
 * Значение попадает в строку метрик: по нему видно, какие регексы и
 * быстрые пути работают, а где запрос уходит в модель.
 */
export enum ChatBranch {
  /** Запрос отсечён фильтром инъекций. */
  INJECTION = 'injection',
  /** Приветствие или вопрос о возможностях: ответ из шаблона. */
  CANNED = 'canned',
  /** Данные заказов показаны шаблоном, без вызова модели. */
  LIVE_TEMPLATE = 'live-template',
  /** Данные заказов отданы модели, она формулирует ответ. */
  LIVE_LLM = 'live-llm',
  /** Ответ из базы знаний. */
  RAG = 'rag',
  /** В базе знаний ничего не нашлось. */
  NO_KNOWLEDGE = 'no-knowledge',
}
